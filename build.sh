#!/bin/zsh
set -eu
task_root="${0:A:h}"
task_build="${1:-$task_root/work/build}"
task_build="${task_build:A}"
task_app="$task_build/stage/Codex Input Unlock.app"
mkdir -p "$task_build/module-cache" "$task_build/cargo" "$task_build/target" "$task_build/tmp"
export TMPDIR="$task_build/tmp/"
export CLANG_MODULE_CACHE_PATH="$task_build/module-cache"
export SWIFT_MODULECACHE_PATH="$task_build/module-cache"
export MACOSX_DEPLOYMENT_TARGET=12.0
CARGO_HOME="$task_build/cargo" CARGO_TARGET_DIR="$task_build/target" cargo build --release --locked --manifest-path "$task_root/Cargo.toml"
mkdir -p "$task_app/Contents/Helpers" "$task_app/Contents/MacOS" "$task_app/Contents/Resources"
cp "$task_root/resources/Info.plist" "$task_app/Contents/Info.plist"
cp "$task_root/resources/ChatGPT.icns" "$task_app/Contents/Resources/ChatGPT.icns"
cp "$task_root/LICENSE" "$task_root/NOTICE.md" "$task_root/THIRD-PARTY-LICENSES.txt" "$task_app/Contents/Resources/"
cp "$task_build/target/release/CodexUnlockAgentRust" "$task_app/Contents/Helpers/CodexUnlockAgentRust"
task_swiftc="$(/usr/bin/xcode-select -p)/Toolchains/XcodeDefault.xctoolchain/usr/bin/swiftc"
task_sdk="$(/usr/bin/xcode-select -p)/Platforms/MacOSX.platform/Developer/SDKs/MacOSX.sdk"
task_arch="$(/usr/bin/uname -m)"
task_flags=(-O -whole-module-optimization -swift-version 5 -target "$task_arch-apple-macosx12.0" -sdk "$task_sdk" -module-cache-path "$task_build/module-cache")
"$task_swiftc" "${task_flags[@]}" "$task_root/BootstrapSources/Core.swift" "$task_root/BootstrapSources/Control.swift" "$task_root/BootstrapSources/Main.swift" -o "$task_app/Contents/Helpers/CodexUnlockAgent"
"$task_swiftc" "${task_flags[@]}" "$task_root/BootstrapSources/GUI.swift" -parse-as-library -o "$task_app/Contents/MacOS/CodexInputUnlock"
/usr/bin/plutil -lint "$task_app/Contents/Info.plist"
/usr/bin/codesign --force --sign - --identifier io.github.trrywui.codex-input-unlock.agent "$task_app/Contents/Helpers/CodexUnlockAgentRust"
/usr/bin/codesign --force --sign - --identifier io.github.trrywui.codex-input-unlock.bootstrap "$task_app/Contents/Helpers/CodexUnlockAgent"
/usr/bin/codesign --force --sign - "$task_app"
/usr/bin/codesign --verify --deep --strict "$task_app"
/usr/bin/ditto "$task_app" "$task_root/Codex Input Unlock.app"
print "已生成正式版：$task_root/Codex Input Unlock.app ($task_arch)"
print "仅生成工作区交付物，未安装、注册或启动应用。"
